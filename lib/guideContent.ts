import type { GuideContentData, GuideSection } from '@/types/guide'
import { prisma } from './prisma'

export async function getGuideContent(): Promise<GuideContentData | null> {
  try {
    const row = await prisma.guideContent.findUnique({
      where: { id: 'singleton' },
    })
    if (row?.content) {
      return JSON.parse(row.content) as GuideContentData
    }
    return null
  } catch (error) {
    console.error('Ошибка чтения руководства из БД:', error)
    return null
  }
}

export async function saveGuideContent(data: GuideContentData): Promise<void> {
  try {
    await prisma.guideContent.upsert({
      where: { id: 'singleton' },
      update: { content: JSON.stringify(data) },
      create: { id: 'singleton', content: JSON.stringify(data) },
    })
  } catch (error) {
    console.error('Ошибка записи руководства в БД:', error)
    throw new Error('Не удалось сохранить руководство')
  }
}

